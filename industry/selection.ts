// 精选的门槛。评分标准本身写在 prompts/selection-score.md；这里只决定“多少分算入选”。
// 每篇资料由评分模型独立打两次分（0–100），两次之和 ≥ 2 × 门槛才进精选，卡片上显示两次的平均分。
// 门槛按信源分级区分：官方一手信源的门槛低一些，媒体和个人的高一些。改了门槛或评分提示词，
// 用 scripts/eval-selection.ts 在你自己标注的样本上重跑一遍，再决定上线（见 docs/selection.md）。
//
// ⚠️ 下面这组数是 AIHOT 在 AI 领域校准出来的，**不是**人文社科领域校准的结果，现在只当起点用。
// 人文社科的噪声结构和医学完全不同：一手信息里征稿通知、学术会议、新书促销、招聘与课程推广极多，
// 媒体端则是立场化长文、书评推介和没有数据支撑的宏大断言；期刊论文里也混着大量相关性当因果、便利取样当普遍规律的东西。
// 真正该校准的是“这条值不值得一个想跟上思想动态的人花五分钟读”。
//
// 2026-10 用 1591 条真实稿件重跑后的实测分布（每篇取两次评分的平均）：
//   T1   （期刊/研究机构）858 篇，平均 45.1，≥58 通过率 44.4%
//   T1_5 （预印本/准官方）195 篇，平均 46.5，≥62 通过率 29.2%
//   T2   （思想媒体/个人）538 篇，平均 32.5，≥72 通过率 **1.3%**
// T2 原为 72，实测几乎不可逾越：538 篇里只有 7 篇达标，而配置本意是「思想媒体正是本站的主要产出」。
// 原因是评分模型对媒体稿系统性给低约 10 分——期刊条目读起来像“研究公告”，媒体长文不是，
// 于是“媒体门槛更高”的来源分级设计与模型自身的偏好叠加，把媒体整片砍掉。
// 故把 T2 对齐 T1_5 的 62。实测效果：思想媒体入选 6 → 61 条，总量 445 → 510（+15%），
// 哲学源 23 → 27。T1 / T1_5 未动。
// 门槛只影响入选判定，分数本身不变：改完重跑 enqueue-analysis.ts --all 即可重算（评分有回执，不重复花钱）。
//
// 校准办法：从现有稿件里挑 100–200 条人工标“该选/不该选”（格式见 industry/gold.example.jsonl），
// 跑 node --env-file=.env scripts/eval-selection.ts --gold .data/gold.jsonl 看准确率，再回来调。

